"""research/<TICKER>.json (written from calls, releases and filings) → <Folder>/content.js, and the script tags in index.html."""
import json, os, re, sys

DASH = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the dashboard repo (scripts/ is inside it)
FOLDER = {'NVDA': 'Nvda', 'SPOT': 'Spot', 'SE': 'Se', 'TBBB': 'Tbbb', 'GOOGL': 'Googl', 'TSM': 'Tsm', 'META': 'Meta', 'NFLX': 'Nflx', 'UBER': 'Uber'}
QRE = re.compile(r"^Q[1-4]'\d\d$")
# steps the researcher inferred rather than read (floors from wording, placeholders, own arithmetic) are left out
INFERRED = re.compile(r"placeholder|stored as (a )?floor|floor (set )?(at|equal to) (the )?(prior|last)|my reading|not a company figure|derived by|\(derived\)|implied by|qualitative only|no number given|\(qualitative\)|floor = |; derived|derived\)", re.I)


def clean(tk, R):
    issues = []
    E = R.get('earnings') or {}
    qs = {k: v for k, v in (E.get('quarters') or {}).items() if QRE.match(k)}
    for k, v in qs.items():
        for f in ('numbers', 'points', 'guidance', 'qa'):
            v[f] = [x for x in (v.get(f) or []) if x]
    if len(qs) != len(E.get('quarters') or {}): issues.append('dropped quarter keys not like Q3\'26')
    topics = R.get('topics') or ['Guidance & outlook']
    G = R.get('guidance') or {}
    per = {}
    for p, mets in (G.get('periods') or {}).items():
        if not (QRE.match(p) or re.match(r'^FY\d{4}$', p)): issues.append('period ' + p); continue
        for k, x in (mets or {}).items():
            lab = ((G.get('labels') or {}).get(k) or [''])[0]
            if 'implied' in lab.lower() or (x or {}).get('qualitative'): issues.append('skipped inferred ' + k); continue
            raw = [s for s in (x or {}).get('steps', []) if isinstance(s, dict) and isinstance(s.get('lo'), (int, float))]
            bad = [s for s in raw if s.get('qualitative') or INFERRED.search(str(s.get('n') or ''))]
            sig = lambda s: (s.get('lo'), s.get('hi'), bool(s.get('floor')))
            badsig = {sig(b) for b in bad}            # reiterations of an inferred value are inferred too
            steps = [s for s in raw if s not in bad and sig(s) not in badsig]
            if len(steps) < len((x or {}).get('steps', [])): issues.append(f'dropped {len((x or {}).get("steps", []))-len(steps)} inferred/qualitative step(s) {p} {k}')
            for s in steps:
                if s.get('hi') is not None and not isinstance(s['hi'], (int, float)): s['hi'] = None
                if s.get('hi') is not None and s['hi'] < s['lo']: s['lo'], s['hi'] = s['hi'], s['lo']
            if steps: per.setdefault(p, {})[k] = {**{kk: vv for kk, vv in x.items() if kk != 'steps'}, 'steps': steps}
    out = {'topics': topics, 'earnings': {'quarters': qs, 'next': E.get('next')} if qs else None,
           'thesis': R.get('thesis'), 'guidance': {'labels': G.get('labels') or {}, 'periods': per} if per else None}
    return out, issues


added = []
for tk, folder in FOLDER.items():
    f = os.path.join(DASH, 'research', tk + '.json')
    if not os.path.exists(f): continue
    try: R = json.load(open(f, encoding='utf-8'))
    except Exception as e: print(tk, 'INVALID JSON', e); continue
    C, issues = clean(tk, R)
    js = ('/* ' + tk + ' — company content: earnings summaries by call and topic, the thesis, and the history of every guide.\n'
          '   Written from the earnings calls, releases, shareholder letters and filings (via Fiscal.ai and Quartr), Nov 2026.\n'
          '   Generated by build_content.py from research/' + tk + '.json — edit the research file and rebuild. */\n'
          '(window.CONTENT = window.CONTENT || {})[' + json.dumps(tk) + '] = ' + json.dumps(C, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(os.path.join(DASH, folder, 'content.js'), 'w', encoding='utf-8', newline='\n').write(js)
    nq = len((C['earnings'] or {}).get('quarters') or {})
    ng = sum(len(x['steps']) for p in ((C['guidance'] or {}).get('periods') or {}).values() for x in p.values())
    print(tk, f'{len(js)//1024} KB', 'quarters', nq, 'thesis', bool(C['thesis']), 'segments', len((C['thesis'] or {}).get('segments') or []), 'guide steps', ng, '|', '; '.join(issues))
    added.append(folder)

H = os.path.join(DASH, 'index.html')
h = open(H, encoding='utf-8').read()
for folder in added:
    tag = f'<script src="{folder}/content.js"></script>\n'
    if tag not in h:
        anchor = f'<script src="{folder}/fiscal.js"></script>\n'
        assert anchor in h, folder
        h = h.replace(anchor, anchor + tag, 1)
open(H, 'w', encoding='utf-8', newline='').write(h)
